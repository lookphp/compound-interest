# 信用卡模拟的独立复算：确认 7,270 / 10,457 不是循环输出的巧合。
def _sim(p=10000.0, apr=0.18, mrate=0.02, floor=50.0, months=60):
    b, paid = p, 0.0
    for _ in range(months):
        b *= 1 + apr / 12
        pay = min(max(b * mrate, floor), b)
        b -= pay
        paid += pay
    return b, paid

